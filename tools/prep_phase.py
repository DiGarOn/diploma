def prep_phase(byte):
    """
    Выполняет подготовительную фазу преобразования 8-битного числа:
    1. Разбивает байт на два 4-битных блока (старшие и младшие биты)
    2. Применяет подстановки p1 и p0 соответственно
    3. Склеивает результаты
    4. Выполняет циклический сдвиг влево на 5 бит
    
    Args:
        byte: 8-битное число (0-255)
    
    Returns:
        Преобразованное 8-битное число
    """
    # Извлекаем старшие 4 бита (биты 7-4)
    high_nibble = (byte >> 4) & 0xF
    
    # Извлекаем младшие 4 бита (биты 3-0)
    low_nibble = byte & 0xF
    
    # Применяем подстановки
    high_sub = p1[high_nibble]
    low_sub = p0[low_nibble]
    
    # Склеиваем результаты: high_sub → биты 7-4, low_sub → биты 3-0
    substituted = (high_sub << 4) | low_sub
    
    # Циклический сдвиг влево на 5 бит
    # Сдвигаем влево на 5 и добавляем биты, которые "выпали" справа
    result = ((substituted << 5) | (substituted >> 3)) & 0xFF
    
    return result

def generate_c_array():
    """
    Генерирует C-массив с результатами prep_phase для всех возможных 8-битных чисел (0-255)
    """
    print("const unsigned char PREP_PHASE_TABLE[256] = {")
    
    for i in range(256):
        if i % 16 == 0:
            print("    ", end="")
        
        result = prep_phase(i)
        
        # Форматируем число с ведущими нулями для красоты
        if i < 255:
            print(f"{result:3d}, ", end="")
        else:
            print(f"{result:3d}", end="")
        
        # Переход на новую строку каждые 16 элементов
        if (i + 1) % 16 == 0:
            print()
    
    print("\n};")


